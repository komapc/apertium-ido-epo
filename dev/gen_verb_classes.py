#!/usr/bin/env python3
"""Generate the vbintr def-cat of apertium-ido-epo.ido-epo.t1x.

The transfer has to know which Ido verbs take no direct object: a noun after one
of them keeps the nominative in Esperanto (La rivero fluas la urbo -> no -n).
The bilingual tags cannot say so, because apertium-epo gives most intransitive
verbs a plain <vblex> paradigm alongside the <vbntr>/<vbser> one.

An Ido stem is intransitive when, for every Esperanto verb it translates to:
  - no Wiktionary marks the Esperanto verb transitive (eniri la domon is fine,
    although apertium-epo classes eniri as vbntr); when they disagree, the label
    of the Ido verb decides, and
  - apertium-epo has a vbntr or vbser paradigm and no vbtr one, or a Wiktionary
    marks the Esperanto verb intransitive and none marks the Ido verb transitive.
Stems already in vbcop or vbser are left out: the copula rules handle them.

Everything comes from the dictionaries and dev/verb_transitivity.tsv (written by
extractor/scripts/parse_verb_transitivity.py), so the list is regeneratable.
Rerun it (make regen-verb-classes) after any bidix or apertium-epo change.
"""
import argparse
import collections
import re
import xml.etree.ElementTree as ET

BEGIN = "<!-- BEGIN GENERATED by dev/gen_verb_classes.py -->"
END = "<!-- END GENERATED -->"


def eo_classes(path):
    root = ET.parse(path).getroot()
    pardefs = {p.get("n"): {s.get("n") for s in p.iter("s")} for p in root.iter("pardef")}
    classes = collections.defaultdict(set)
    for entry in root.iter("e"):
        lemma = entry.get("lm")
        if not lemma:
            continue
        for par in entry.findall("par"):
            classes[lemma] |= pardefs.get(par.get("n"), set()) & {"vbtr", "vbntr", "vbser"}
    return classes


def ido_verbs(path):
    """Map each Ido verb stem to the Esperanto verbs it translates to (LR rows)."""
    verbs = collections.defaultdict(set)
    for entry in ET.parse(path).getroot().iter("e"):
        pair = entry.find("p")
        if pair is None or entry.get("r") == "RL":
            continue
        left, right = pair.find("l"), pair.find("r")
        if [c.get("n") for c in left] != ["vblex"] or not left.text or not right.text:
            continue
        if right.find("b") is not None:
            continue
        verbs[left.text].add(right.text)
    return verbs


def read_labels(path):
    """Map (language, verb) to {source Wiktionary: labels}."""
    labels = collections.defaultdict(dict)
    with open(path, encoding="utf-8") as rows:
        for row in rows:
            lang, verb, source, found = row.rstrip("\n").split("\t")
            labels[lang, verb][source] = set(found.split(","))
    return labels


def union(labels):
    return set().union(*labels.values()) if labels else set()


def takes_object(eo, ido, labels):
    """Whether the Wiktionaries let the Esperanto verb take a direct object."""
    sources = labels["eo", eo].values()
    if {"tr"} in sources and {"intr"} in sources:
        # alveni: fr says transitive, en intransitive; the Ido verb's own label decides
        own = labels["io", ido]
        return "tr" in (own.get("io") or union(own))
    return any("tr" in found for found in sources)


def is_intransitive(stem, eo, classes, labels):
    ido = stem + "ar"
    if takes_object(eo, ido, labels):
        return False
    if classes[eo] & {"vbntr", "vbser"} and "vbtr" not in classes[eo]:
        return True
    return "intr" in union(labels["eo", eo]) and "tr" not in union(labels["io", ido])


def intransitive(verbs, classes, labels, excluded):
    return sorted(
        stem for stem, eos in verbs.items()
        if stem not in excluded and all(is_intransitive(stem, e, classes, labels) for e in eos)
    )


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--bidix", required=True)
    ap.add_argument("--monodix", required=True)
    ap.add_argument("--labels", required=True)
    ap.add_argument("--t1x", required=True)
    args = ap.parse_args()

    text = open(args.t1x, encoding="utf-8").read()
    excluded = set()
    for cat in ("vbcop", "vbser"):
        items = re.search(rf'<def-cat n="{cat}">(.*?)</def-cat>', text, re.S).group(1)
        excluded |= set(re.findall(r'lemma="([^"]+)"', items))

    stems = intransitive(ido_verbs(args.bidix), eo_classes(args.monodix), read_labels(args.labels), excluded)
    items = "".join(f'      <cat-item lemma="{s}" tags="vblex.*"/>\n' for s in stems)
    block = f"{BEGIN}\n{items}      {END}"
    pattern = re.compile(re.escape(BEGIN) + ".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise SystemExit(f"{args.t1x}: generated markers not found")
    with open(args.t1x, "w", encoding="utf-8") as out:
        out.write(pattern.sub(lambda _: block, text))
    print(f"vbintr: {len(stems)} stems")


if __name__ == "__main__":
    main()
